"""
Pydantic data models — the canonical data shapes used across the entire agent.
Every module speaks in these types; no raw dicts passed between layers.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator


def _utcnow() -> datetime:
    """Timezone-aware UTC now. Replaces deprecated datetime.utcnow()."""
    return datetime.now(timezone.utc)


# ── Quote (single price tick) ─────────────────────────────────────────────────

class Quote(BaseModel):
    """A single OHLCV data point."""
    timestamp: datetime
    open: float
    high: float
    low: float
    close: float
    volume: int
    vwap: float | None = None       # populated by technical layer


# ── Fundamentals ──────────────────────────────────────────────────────────────

class Fundamentals(BaseModel):
    """Key fundamental metrics for a stock / ETF."""
    market_cap: float | None = None          # in local currency (INR / USD)
    pe_ratio: float | None = None
    pb_ratio: float | None = None
    eps: float | None = None
    revenue_ttm: float | None = None         # trailing 12-month revenue
    net_income_ttm: float | None = None
    ebitda: float | None = None
    debt_to_equity: float | None = None
    free_cash_flow: float | None = None
    dividend_yield: float | None = None
    beta: float | None = None
    week_52_high: float | None = None
    week_52_low: float | None = None
    avg_volume_30d: int | None = None
    shares_outstanding: float | None = None
    return_on_equity: float | None = None
    profit_margin: float | None = None


# ── News Item ─────────────────────────────────────────────────────────────────

class NewsItem(BaseModel):
    """A single news headline."""
    title: str
    publisher: str | None = None
    published_at: datetime | None = None
    url: str | None = None
    summary: str | None = None              # LLM-generated 1-sentence summary
    sentiment: Literal["positive", "neutral", "negative"] | None = None


# ── Stock Snapshot (main data object passed to analyst) ───────────────────────

class StockSnapshot(BaseModel):
    """
    Complete data snapshot for a single ticker.
    This is the primary input to the analyst engine.
    """
    ticker: str
    name: str | None = None
    market: Literal["india", "us"]
    sector: str | None = None
    currency: Literal["INR", "USD"]
    is_etf: bool = False                    # set explicitly by fetcher (not guessed)

    # Current price info
    current_price: float
    price_change_pct_1d: float | None = None
    price_change_pct_1w: float | None = None
    price_change_pct_1m: float | None = None
    price_change_pct_3m: float | None = None
    price_change_pct_1y: float | None = None

    # OHLCV history (most recent ~252 trading days for technical analysis)
    history: list[Quote] = Field(default_factory=list)

    # Fundamentals
    fundamentals: Fundamentals = Field(default_factory=Fundamentals)

    # News
    recent_news: list[NewsItem] = Field(default_factory=list)

    # Metadata
    fetched_at: datetime = Field(default_factory=_utcnow)
    data_source: str = "yfinance"

    @field_validator("ticker")
    @classmethod
    def uppercase_ticker(cls, v: str) -> str:
        return v.upper()

    def price_summary(self) -> str:
        """One-line price summary for logging / quick display."""
        currency_sym = "₹" if self.currency == "INR" else "$"
        chg = f"{self.price_change_pct_1d:+.2f}%" if self.price_change_pct_1d is not None else "N/A"
        return f"{self.ticker} @ {currency_sym}{self.current_price:,.2f} ({chg} today)"


Strategy = Literal["scalping", "intraday", "swing", "positional"]


# ── Trade Signal ──────────────────────────────────────────────────────────────

class TradeSignal(BaseModel):
    """A trading signal generated by the signal engine."""
    model_config = ConfigDict(strict=True)

    ticker: str
    market: Literal["india", "us"]
    strategy: Strategy
    direction: Literal["BUY", "SELL", "HOLD"]
    entry_price: float
    stop_loss: float
