# ── Position ──────────────────────────────────────────────────────────────────

class Position(BaseModel):
    """An open position in the portfolio."""
    ticker: str
    market: Literal["india", "us"]
    strategy: Strategy
    direction: Literal["LONG", "SHORT"]
    quantity: int
    avg_cost: float
    current_price: float | None = None
    stop_loss: float | None = None
    target_price: float | None = None
    is_paper: bool = True
    opened_at: datetime = Field(default_factory=_utcnow)

    @property
    def unrealized_pnl(self) -> float | None:
        if self.current_price is None:
            return None
        if self.direction == "LONG":
            return (self.current_price - self.avg_cost) * self.quantity
        return (self.avg_cost - self.current_price) * self.quantity

    @property
    def unrealized_pnl_pct(self) -> float | None:
        if self.current_price is None or self.avg_cost == 0:
            return None
        if self.direction == "LONG":
            return ((self.current_price - self.avg_cost) / self.avg_cost) * 100
        return ((self.avg_cost - self.current_price) / self.avg_cost) * 100


# ── Advisory Holding ──────────────────────────────────────────────────────────

class AdvisoryHolding(BaseModel):
    """An advisory portfolio holding (recommended, not auto-executed)."""
    ticker: str
    name: str | None = None
    market: Literal["india", "us"]
    horizon: Literal["short_term", "long_term"]
    entry_price: float
    recommended_at: datetime
    quantity_suggested: int | None = None
    stop_loss: float | None = None
    target_price: float | None = None
    current_price: float | None = None
    thesis: str | None = None
    invalidation_trigger: str | None = None

    @property
    def return_pct(self) -> float | None:
        if self.current_price is None or self.entry_price == 0:
            return None
        return ((self.current_price - self.entry_price) / self.entry_price) * 100

    @property
    def days_held(self) -> int:
        return (datetime.now(timezone.utc) - self.recommended_at.replace(tzinfo=timezone.utc)).days


